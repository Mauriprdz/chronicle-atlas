// Generates public/css/themes.css from server/themes.js
// Each topic gets a [data-theme="slug"] block of CSS custom properties (Requirements 5.4).
import fs from 'node:fs';
import { THEMES } from '../server/themes.js';

const enc = (svg) => `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;

function pattern(motif, c) {
  const col = c.replace('#', '%23');
  const svgs = {
    waves: `<svg xmlns='http://www.w3.org/2000/svg' width='120' height='40'><path d='M0 20 Q15 5 30 20 T60 20 T90 20 T120 20' fill='none' stroke='${c}' stroke-width='2' opacity='.35'/></svg>`,
    mountains: `<svg xmlns='http://www.w3.org/2000/svg' width='120' height='60'><path d='M0 60 L30 20 L50 40 L75 8 L105 45 L120 30' fill='none' stroke='${c}' stroke-width='2' opacity='.3'/></svg>`,
    dunes: `<svg xmlns='http://www.w3.org/2000/svg' width='160' height='50'><path d='M0 35 C40 10 80 50 160 25' fill='none' stroke='${c}' stroke-width='2' opacity='.3'/></svg>`,
    columns: `<svg xmlns='http://www.w3.org/2000/svg' width='60' height='60'><rect x='10' y='8' width='8' height='44' fill='${c}' opacity='.16'/><rect x='6' y='4' width='16' height='4' fill='${c}' opacity='.25'/></svg>`,
    leaves: `<svg xmlns='http://www.w3.org/2000/svg' width='80' height='80'><ellipse cx='40' cy='40' rx='22' ry='8' transform='rotate(35 40 40)' fill='${c}' opacity='.18'/></svg>`,
    tiles: `<svg xmlns='http://www.w3.org/2000/svg' width='48' height='48'><path d='M24 4 L44 24 L24 44 L4 24 Z' fill='none' stroke='${c}' stroke-width='1.5' opacity='.3'/><circle cx='24' cy='24' r='4' fill='${c}' opacity='.25'/></svg>`,
    coins: `<svg xmlns='http://www.w3.org/2000/svg' width='70' height='70'><circle cx='35' cy='35' r='14' fill='none' stroke='${c}' stroke-width='2' opacity='.3'/><circle cx='35' cy='35' r='9' fill='${c}' opacity='.15'/></svg>`,
    spiral: `<svg xmlns='http://www.w3.org/2000/svg' width='80' height='80'><path d='M40 40 m-18 0 a18 18 0 1 1 36 0 a13 13 0 1 1 -26 0 a8 8 0 1 1 16 0' fill='none' stroke='${c}' stroke-width='2' opacity='.3'/></svg>`,
    sun: `<svg xmlns='http://www.w3.org/2000/svg' width='90' height='90'><circle cx='45' cy='45' r='8' fill='${c}' opacity='.25'/><g stroke='${c}' stroke-width='2' opacity='.25'><line x1='45' y1='25' x2='45' y2='15'/><line x1='45' y1='65' x2='45' y2='75'/><line x1='25' y1='45' x2='15' y2='45'/><line x1='65' y1='45' x2='75' y2='45'/></g></svg>`,
    stars: `<svg xmlns='http://www.w3.org/2000/svg' width='90' height='90'><circle cx='15' cy='20' r='1.5' fill='${c}' opacity='.5'/><circle cx='60' cy='45' r='1' fill='${c}' opacity='.5'/><circle cx='35' cy='75' r='1.2' fill='${c}' opacity='.5'/></svg>`,
  };
  void col;
  return enc(svgs[motif] || svgs.stars);
}

let css = `/* AUTO-GENERATED by scripts/build-themes.mjs - do not edit by hand */\n`;
for (const t of THEMES) {
  const selector = t.slug === 'atlas' ? `:root, [data-theme="atlas"]` : `[data-theme="${t.slug}"]`;
  css += `${selector} {
  --bg: ${t.bg}; --surface: ${t.surface}; --surface-2: ${t.surface2};
  --text: ${t.text}; --muted: ${t.muted}; --border: ${t.border};
  --accent: ${t.accent}; --accent-2: ${t.accent2}; --on-accent: ${t.onAccent};
  --font-display: ${t.display}; --font-body: ${t.body};
  --pattern: ${pattern(t.motif, t.accent)};
  color-scheme: ${t.mode};
}\n`;
}
fs.writeFileSync(new URL('../public/css/themes.css', import.meta.url), css);
console.log(`Wrote ${THEMES.length} themes to public/css/themes.css`);
